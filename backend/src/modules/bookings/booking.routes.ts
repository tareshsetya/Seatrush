import { Router } from 'express';
import { bookingController } from './booking.controller.js';
import { requireAuth } from '../auth/auth.middleware.js';
const router=Router();
router.use(requireAuth);
router.post('/',(req,res,next)=>bookingController.create(req,res,next));
router.get('/mine',(req,res,next)=>bookingController.getByUser(req,res,next));
router.get('/user/:userId',(req,res,next)=>bookingController.getByUser(req,res,next));
router.get('/ref/:ref',(req,res,next)=>bookingController.getByReference(req,res,next));
router.get('/:id',(req,res,next)=>bookingController.getById(req,res,next));
export default router;
